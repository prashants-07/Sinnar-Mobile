for size in (16,32):
    data=(images/f'favicon-{size}x{size}.png').read_bytes()
    entries.append(struct.pack('<BBBBHHII',size,size,0,0,1,32,len(data),offset));payload+=data;offset+=len(data)
(images/'favicon.ico').write_bytes(struct.pack('<HHH',0,1,2)+b''.join(entries)+payload)
