def rounded(x,y,left,top,width,height,radius):
    if not(left<=x<=left+width and top<=y<=top+height):return False
    cx=min(max(x,left+radius),left+width-radius);cy=min(max(y,top+radius),top+height-radius)
    return (x-cx)**2+(y-cy)**2<=radius**2
def polygon(x,y,points):
    inside=False;j=len(points)-1
    for i,(a,b) in enumerate(points):
        c,d=points[j]
        if (b>y)!=(d>y) and x<(c-a)*(y-b)/(d-b)+a:inside=not inside
        j=i
    return inside
def color(x,y):
    blue=(36,89,237,255);white=(255,255,255,255);clear=(0,0,0,0)
    if not rounded(x,y,0,0,48,48,12):return clear
    c=blue
    if rounded(x,y,14,7,20,34,5):c=white
    if rounded(x,y,17,10,14,26,3):c=blue
    if rounded(x,y,21,12,6,2,1):c=white
    if polygon(x,y,[(25,18),(20,26),(24,26),(23,32),(29,22),(25,22),(26,18)]):c=white
    if (x-24)**2+(y-38)**2<=1:c=blue
    return c
def png(size):
    factor=4;raw=bytearray()
    for row in range(size):
        raw.append(0)
        for col in range(size):
            samples=[color((col+(sx+.5)/factor)*48/size,(row+(sy+.5)/factor)*48/size) for sy in range(factor) for sx in range(factor)]
            alpha=sum(c[3] for c in samples)
            # Premultiplied averaging avoids dark halos around transparent rounded corners.
            raw.extend([round(sum(c[k]*c[3] for c in samples)/alpha) if alpha else 0 for k in range(3)]+[round(alpha/(factor*factor))])
    def chunk(name,data):return struct.pack('>I',len(data))+name+data+struct.pack('>I',zlib.crc32(name+data)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',size,size,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b'')
for size in (16,32,192): (images/f'favicon-{size}x{size}.png').write_bytes(png(size))
(images/'apple-touch-icon.png').write_bytes(png(180))
